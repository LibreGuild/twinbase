struct CatTable {
    name: &'static str,
    columns: &'static [(&'static str, &'static str)],
    rows: Vec<Vec<Value>>,
}

fn t(s: impl Into<String>) -> Value {
    Value::Text(s.into())
}
fn i(n: impl Into<i64>) -> Value {
    Value::Integer(n.into())
}
fn b(v: bool) -> Value {
    Value::Integer(v as i64)
}
fn null() -> Value {
    Value::Null
}
fn opt(s: Option<&str>) -> Value {
    s.map(t).unwrap_or(Value::Null)
}

/// Declared types of emulated catalog columns, keyed by lower-case `(table, column)`.
pub type CatalogTypes = std::collections::HashMap<(String, String), SqlType>;

fn create_cat_tables(conn: &Connection, db: &str, tables: Vec<CatTable>, types: &mut CatalogTypes) -> Result<()> {
    let q = quote_ident(db);
    let mut sql = String::new();
    for table in &tables {
        let cols: Vec<String> = table
            .columns
            .iter()
            .map(|(n, ty)| {
                let parsed = SqlType::parse_simple(ty, Dialect::Postgres);
                let decl = parsed.storage().sqlite_decl();
                types.insert((table.name.to_ascii_lowercase(), n.to_ascii_lowercase()), parsed);
                format!("{} {}", quote_ident(n), decl)
            })
            .collect();
        sql.push_str(&format!("DROP TABLE IF EXISTS {q}.{};\n", quote_ident(table.name)));
        sql.push_str(&format!("CREATE TABLE {q}.{} ({});\n", quote_ident(table.name), cols.join(", ")));
    }
    conn.execute_batch(&sql).map_err(|e| EngineError::internal(format!("catalog setup: {e}")))?;
    for table in tables {
        if table.rows.is_empty() {
            continue;
        }
        let placeholders = vec!["?"; table.columns.len()].join(", ");
        let mut stmt = conn
            .prepare(&format!("INSERT INTO {q}.{} VALUES ({placeholders})", quote_ident(table.name)))
            .map_err(|e| EngineError::internal(e.to_string()))?;
        for row in table.rows {
            stmt.execute(rusqlite::params_from_iter(row.iter()))
                .map_err(|e| EngineError::internal(format!("catalog row for {}: {e}", table.name)))?;
        }
    }
    Ok(())
}

