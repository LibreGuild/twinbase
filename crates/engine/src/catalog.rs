//! Schema metadata. Every schema (PostgreSQL) or database (MySQL) is one SQLite file holding the
//! user's tables plus `_tb_meta` (definitions in the original dialect) and `_tb_seq` (sequences).
//! The in-memory [`Catalog`] is rebuilt from those tables and is the source of truth for types.

use std::collections::BTreeMap;

use rusqlite::{Connection, params, types::Value};
use serde::{Deserialize, Serialize};

use crate::Dialect;
use crate::error::{EngineError, Result};
use crate::types::SqlType;

pub const META_DDL: &str = "CREATE TABLE IF NOT EXISTS {s}._tb_meta (kind TEXT NOT NULL, name TEXT NOT NULL, def TEXT NOT NULL, PRIMARY KEY (kind, name));
CREATE TABLE IF NOT EXISTS {s}._tb_seq (name TEXT PRIMARY KEY, last_value INTEGER NOT NULL, is_called INTEGER NOT NULL, increment INTEGER NOT NULL DEFAULT 1, start_value INTEGER NOT NULL DEFAULT 1, min_value INTEGER, max_value INTEGER, owner TEXT);";

/// Internal tables are hidden from every catalog view.
pub fn is_internal(name: &str) -> bool {
    name.starts_with("_tb_") || name.starts_with("sqlite_")
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DefaultExpr {
    /// Expression as written in the dialect (shown to users and catalogs).
    pub display: String,
    /// Translated SQLite expression (already wrapped in `tb_cast`).
    pub sql: String,
    /// SQL Server: the default constraint's name, when the DDL gave one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
}

impl ColumnDef {
    /// SQL Server: the name of this column's default constraint.
    pub fn default_constraint_name(&self, table: &str) -> Option<String> {
        let d = self.default.as_ref().filter(|_| self.identity.is_none())?;
        Some(d.name.clone().unwrap_or_else(|| format!("DF__{table}__{}", self.name)))
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Identity {
    /// PostgreSQL `SERIAL`/`BIGSERIAL`.
    Serial { sequence: String },
    /// PostgreSQL `GENERATED ALWAYS AS IDENTITY`.
    Always { sequence: String },
    /// PostgreSQL `GENERATED BY DEFAULT AS IDENTITY`.
    ByDefault { sequence: String },
    /// MySQL `AUTO_INCREMENT`.
    AutoIncrement { sequence: String },
}

impl Identity {
    pub fn sequence(&self) -> &str {
        match self {
            Identity::Serial { sequence }
            | Identity::Always { sequence }
            | Identity::ByDefault { sequence }
            | Identity::AutoIncrement { sequence } => sequence,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ColumnDef {
    pub name: String,
    pub ty: SqlType,
    /// Type as written by the user (e.g. `varchar(255)`).
    pub type_text: String,
    pub nullable: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub default: Option<DefaultExpr>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub identity: Option<Identity>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub comment: Option<String>,
    /// MySQL `ON UPDATE CURRENT_TIMESTAMP`.
    #[serde(default)]
    pub on_update_now: bool,
    #[serde(default)]
    pub unsigned: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct KeyDef {
    pub name: String,
    pub columns: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ForeignKeyDef {
    pub name: String,
    pub columns: Vec<String>,
    pub ref_schema: String,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub on_delete: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub on_update: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CheckDef {
    pub name: String,
    pub display: String,
    pub sql: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct IndexDef {
    pub name: String,
    pub columns: Vec<String>,
    #[serde(default)]
    pub descending: Vec<bool>,
    pub unique: bool,
    /// Partial index predicate (translated SQLite expression).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub where_sql: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TableDef {
    pub name: String,
    pub columns: Vec<ColumnDef>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub primary_key: Option<KeyDef>,
    #[serde(default)]
    pub uniques: Vec<KeyDef>,
    #[serde(default)]
    pub foreign_keys: Vec<ForeignKeyDef>,
    #[serde(default)]
    pub checks: Vec<CheckDef>,
    #[serde(default)]
    pub indexes: Vec<IndexDef>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub comment: Option<String>,
}

impl TableDef {
    pub fn column(&self, name: &str) -> Option<&ColumnDef> {
        self.columns.iter().find(|c| c.name == name).or_else(|| self.columns.iter().find(|c| c.name.eq_ignore_ascii_case(name)))
    }

    pub fn column_index(&self, name: &str) -> Option<usize> {
        self.columns.iter().position(|c| c.name == name).or_else(|| self.columns.iter().position(|c| c.name.eq_ignore_ascii_case(name)))
    }

    pub fn column_mut(&mut self, name: &str) -> Option<&mut ColumnDef> {
        let idx = self.column_index(name)?;
        self.columns.get_mut(idx)
    }

    /// Every constraint name used by this table.
    pub fn constraint_names(&self) -> Vec<&str> {
        let mut v: Vec<&str> = Vec::new();
        if let Some(pk) = &self.primary_key {
            v.push(&pk.name);
        }
        v.extend(self.uniques.iter().map(|u| u.name.as_str()));
        v.extend(self.foreign_keys.iter().map(|f| f.name.as_str()));
        v.extend(self.checks.iter().map(|c| c.name.as_str()));
        v
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ViewDef {
    pub name: String,
    /// Definition as written by the user.
    pub definition: String,
    /// Translated SQLite query.
    pub sql: String,
    #[serde(default)]
    pub columns: Vec<(String, SqlType)>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct EnumDef {
    pub name: String,
    pub values: Vec<String>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct SequenceInfo {
    pub name: String,
    pub last_value: i64,
    pub is_called: bool,
    pub increment: i64,
    pub start_value: i64,
    pub min_value: Option<i64>,
    pub max_value: Option<i64>,
    pub owner: Option<String>,
}

#[derive(Debug, Clone, Default)]
pub struct SchemaDef {
    pub name: String,
    pub tables: BTreeMap<String, TableDef>,
    pub views: BTreeMap<String, ViewDef>,
    pub enums: BTreeMap<String, EnumDef>,
    pub sequences: BTreeMap<String, SequenceInfo>,
    pub comments: BTreeMap<String, String>,
}

#[derive(Debug, Clone)]
pub struct Catalog {
    pub dialect: Dialect,
    pub database: String,
    pub schemas: BTreeMap<String, SchemaDef>,
}

impl Catalog {
    pub fn empty(dialect: Dialect, database: &str) -> Self {
        Self { dialect, database: database.to_owned(), schemas: BTreeMap::new() }
    }

    /// Load metadata from every attached schema file.
    pub fn load(conn: &Connection, dialect: Dialect, database: &str, schemas: &[String]) -> Result<Self> {
        let mut cat = Catalog::empty(dialect, database);
        for schema in schemas {
            let q = quote_ident(schema);
            let mut sd = SchemaDef { name: schema.clone(), ..Default::default() };
            let mut stmt = conn
                .prepare(&format!("SELECT kind, name, def FROM {q}._tb_meta"))
                .map_err(|e| EngineError::internal(format!("catalog load failed for {schema}: {e}")))?;
            let rows = stmt
                .query_map([], |r| Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?, r.get::<_, String>(2)?)))
                .map_err(|e| EngineError::internal(e.to_string()))?;
            for row in rows {
                let (kind, name, def) = row.map_err(|e| EngineError::internal(e.to_string()))?;
                match kind.as_str() {
                    "table" => {
                        if let Ok(t) = serde_json::from_str::<TableDef>(&def) {
                            sd.tables.insert(name, t);
                        }
                    }
                    "view" => {
                        if let Ok(v) = serde_json::from_str::<ViewDef>(&def) {
                            sd.views.insert(name, v);
                        }
                    }
                    "enum" => {
                        if let Ok(e) = serde_json::from_str::<EnumDef>(&def) {
                            sd.enums.insert(name, e);
                        }
                    }
                    "comment" => {
                        sd.comments.insert(name, def);
                    }
                    _ => {}
                }
            }
            let mut stmt = conn
                .prepare(&format!(
                    "SELECT name, last_value, is_called, increment, start_value, min_value, max_value, owner FROM {q}._tb_seq"
                ))
                .map_err(|e| EngineError::internal(e.to_string()))?;
            let rows = stmt
                .query_map([], |r| {
                    Ok(SequenceInfo {
                        name: r.get(0)?,
                        last_value: r.get(1)?,
                        is_called: r.get::<_, i64>(2)? != 0,
                        increment: r.get(3)?,
                        start_value: r.get(4)?,
                        min_value: r.get(5)?,
                        max_value: r.get(6)?,
                        owner: r.get(7)?,
                    })
                })
                .map_err(|e| EngineError::internal(e.to_string()))?;
            for row in rows {
                let s = row.map_err(|e| EngineError::internal(e.to_string()))?;
                sd.sequences.insert(s.name.clone(), s);
            }
            cat.schemas.insert(schema.clone(), sd);
        }
        Ok(cat)
    }

    pub fn schema(&self, name: &str) -> Option<&SchemaDef> {
        self.schemas.get(name).or_else(|| {
            if self.dialect.case_insensitive_names() { self.schemas.values().find(|s| s.name.eq_ignore_ascii_case(name)) } else { None }
        })
    }

    pub fn table(&self, schema: &str, name: &str) -> Option<&TableDef> {
        let s = self.schema(schema)?;
        s.tables.get(name).or_else(|| {
            if self.dialect.case_insensitive_names() { s.tables.values().find(|t| t.name.eq_ignore_ascii_case(name)) } else { None }
        })
    }

    pub fn view(&self, schema: &str, name: &str) -> Option<&ViewDef> {
        let s = self.schema(schema)?;
        s.views.get(name).or_else(|| s.views.values().find(|v| self.dialect.case_insensitive_names() && v.name.eq_ignore_ascii_case(name)))
    }

    /// Find the schema holding `name` (table or view), searching `path` in order.
    pub fn resolve_relation(&self, name: &str, path: &[String]) -> Option<(String, Relation<'_>)> {
        for schema in path {
            if let Some(t) = self.table(schema, name) {
                return Some((self.schema(schema).map(|s| s.name.clone()).unwrap_or_else(|| schema.clone()), Relation::Table(t)));
            }
            if let Some(v) = self.view(schema, name) {
                return Some((self.schema(schema).map(|s| s.name.clone()).unwrap_or_else(|| schema.clone()), Relation::View(v)));
            }
        }
        None
    }

    pub fn enum_values(&self, name: &str, path: &[String]) -> Option<Vec<String>> {
        let (schema, bare) = match name.split_once('.') {
            Some((s, n)) => (Some(s), n),
            None => (None, name),
        };
        let bare = bare.trim_matches('"');
        let candidates: Vec<&str> = match schema {
            Some(s) => vec![s],
            None => path.iter().map(String::as_str).collect(),
        };
        candidates.into_iter().find_map(|s| self.schema(s)?.enums.get(bare).map(|e| e.values.clone()))
    }

    /// Tables in other schemas whose foreign keys reference `schema.table`.
    pub fn referencing(&self, schema: &str, table: &str) -> Vec<(String, String, ForeignKeyDef)> {
        let mut out = Vec::new();
        for sd in self.schemas.values() {
            for t in sd.tables.values() {
                for fk in &t.foreign_keys {
                    if fk.ref_schema == schema && fk.ref_table == table && !(sd.name == schema && t.name == table) {
                        out.push((sd.name.clone(), t.name.clone(), fk.clone()));
                    }
                }
            }
        }
        out
    }
}

pub enum Relation<'a> {
    Table(&'a TableDef),
    View(&'a ViewDef),
}

pub fn quote_ident(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}

pub fn quote_literal(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// Persist a table definition into its schema's metadata.
pub fn save_table(conn: &Connection, schema: &str, t: &TableDef) -> Result<()> {
    save_meta(conn, schema, "table", &t.name, &serde_json::to_string(t).expect("table def serializes"))
}

pub fn save_meta(conn: &Connection, schema: &str, kind: &str, name: &str, def: &str) -> Result<()> {
    conn.execute(
        &format!("INSERT OR REPLACE INTO {}._tb_meta (kind, name, def) VALUES (?1, ?2, ?3)", quote_ident(schema)),
        params![kind, name, def],
    )
    .map(|_| ())
    .map_err(|e| EngineError::internal(e.to_string()))
}

pub fn delete_meta(conn: &Connection, schema: &str, kind: &str, name: &str) -> Result<()> {
    conn.execute(&format!("DELETE FROM {}._tb_meta WHERE kind = ?1 AND name = ?2", quote_ident(schema)), params![kind, name])
        .map(|_| ())
        .map_err(|e| EngineError::internal(e.to_string()))
}

/// Render the SQLite `CREATE TABLE` for a table definition. With `qualified` false the text is
/// what SQLite stores in `sqlite_schema` (used when rewriting a table definition in place).
pub fn render_create_table(schema: &str, t: &TableDef, dialect: Dialect, table_name: &str, qualified: bool) -> String {
    let mut parts: Vec<String> = Vec::new();
    for c in &t.columns {
        // `INT` (not `INTEGER`) so a single-column integer primary key never becomes a rowid
        // alias: SQLite would then skip the column DEFAULT (nextval) for omitted values.
        let decl = match c.ty.storage() {
            crate::types::Storage::Integer => "INT",
            other => other.sqlite_decl(),
        };
        let mut s = format!("{} {decl}", quote_ident(&c.name));
        if dialect == Dialect::MySql && c.ty.is_textual() {
            s.push_str(" COLLATE NOCASE");
        }
        if !c.nullable {
            s.push_str(" NOT NULL");
        }
        if let Some(d) = &c.default {
            s.push_str(&format!(" DEFAULT ({})", d.sql));
        }
        parts.push(s);
    }
    if let Some(pk) = &t.primary_key {
        parts.push(format!("CONSTRAINT {} PRIMARY KEY ({})", quote_ident(&pk.name), join_idents(&pk.columns)));
    }
    // UNIQUE constraints are separate unique indexes (see `unique_index`), so they can be added
    // and dropped later without rebuilding the table.
    for fk in &t.foreign_keys {
        // SQLite can only enforce foreign keys within one database file (schema).
        if fk.ref_schema != schema {
            continue;
        }
        let mut s = format!(
            "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
            quote_ident(&fk.name),
            join_idents(&fk.columns),
            quote_ident(&fk.ref_table),
            join_idents(&fk.ref_columns)
        );
        if let Some(a) = &fk.on_delete {
            s.push_str(&format!(" ON DELETE {a}"));
        }
        if let Some(a) = &fk.on_update {
            s.push_str(&format!(" ON UPDATE {a}"));
        }
        parts.push(s);
    }
    for c in &t.checks {
        parts.push(format!("CONSTRAINT {} CHECK ({})", quote_ident(&c.name), c.sql));
    }
    let name = if qualified { format!("{}.{}", quote_ident(schema), quote_ident(table_name)) } else { quote_ident(table_name) };
    format!("CREATE TABLE {name} (\n  {}\n)", parts.join(",\n  "))
}

/// The unique index backing a UNIQUE constraint.
pub fn unique_index(key: &KeyDef) -> IndexDef {
    IndexDef { name: key.name.clone(), columns: key.columns.clone(), descending: vec![], unique: true, where_sql: None }
}

pub fn render_create_index(schema: &str, table: &str, idx: &IndexDef) -> String {
    let cols: Vec<String> = idx
        .columns
        .iter()
        .enumerate()
        .map(|(i, c)| {
            let desc = idx.descending.get(i).copied().unwrap_or(false);
            format!("{}{}", quote_ident(c), if desc { " DESC" } else { "" })
        })
        .collect();
    let mut sql = format!(
        "CREATE {}INDEX {}.{} ON {} ({})",
        if idx.unique { "UNIQUE " } else { "" },
        quote_ident(schema),
        quote_ident(&idx.name),
        quote_ident(table),
        cols.join(", ")
    );
    if let Some(w) = &idx.where_sql {
        sql.push_str(&format!(" WHERE {w}"));
    }
    sql
}

pub fn join_idents(cols: &[String]) -> String {
    cols.iter().map(|c| quote_ident(c)).collect::<Vec<_>>().join(", ")
}

/// Stable 32-bit object id for PostgreSQL catalogs.
pub fn oid_for(parts: &[&str]) -> u32 {
    let mut h: u32 = 0x811c9dc5;
    for p in parts {
        for b in p.bytes().chain(std::iter::once(0u8)) {
            h ^= b as u32;
            h = h.wrapping_mul(0x01000193);
        }
    }
    16384 + (h % 1_000_000_000)
}

pub fn schema_oid(schema: &str) -> u32 {
    match schema {
        "pg_catalog" => 11,
        "public" => 2200,
        "information_schema" => 13000,
        _ => oid_for(&["ns", schema]),
    }
}

pub fn table_oid(schema: &str, table: &str) -> u32 {
    oid_for(&["rel", schema, table])
}

pub fn enum_oid(schema: &str, name: &str) -> u32 {
    oid_for(&["type", schema, name])
}

/// MySQL/PostgreSQL rendering of a table as `CREATE TABLE` in the original dialect.
pub fn render_dialect_ddl(schema: &str, t: &TableDef, dialect: Dialect) -> String {
    let q = |s: &str| match dialect {
        Dialect::MySql => format!("`{}`", s.replace('`', "``")),
        _ => quote_ident_if_needed(s),
    };
    let mut parts = Vec::new();
    for c in &t.columns {
        let mut s = format!("{} {}", q(&c.name), if c.type_text.is_empty() { c.ty.display(dialect) } else { c.type_text.clone() });
        if !c.nullable {
            s.push_str(" NOT NULL");
        }
        if let Some(d) = &c.default
            && !matches!(c.identity, Some(Identity::Serial { .. }) | Some(Identity::AutoIncrement { .. }))
        {
            s.push_str(&format!(" DEFAULT {}", d.display));
        }
        match &c.identity {
            Some(Identity::AutoIncrement { .. }) => s.push_str(" AUTO_INCREMENT"),
            Some(Identity::Always { .. }) => s.push_str(" GENERATED ALWAYS AS IDENTITY"),
            Some(Identity::ByDefault { .. }) => s.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
            _ => {}
        }
        if c.on_update_now {
            s.push_str(" ON UPDATE CURRENT_TIMESTAMP");
        }
        if dialect == Dialect::MySql
            && let Some(cm) = &c.comment
        {
            s.push_str(&format!(" COMMENT {}", quote_literal(cm)));
        }
        parts.push(s);
    }
    let cols = |v: &[String]| v.iter().map(|c| q(c)).collect::<Vec<_>>().join(", ");
    if let Some(pk) = &t.primary_key {
        if dialect == Dialect::MySql {
            parts.push(format!("PRIMARY KEY ({})", cols(&pk.columns)));
        } else {
            parts.push(format!("CONSTRAINT {} PRIMARY KEY ({})", q(&pk.name), cols(&pk.columns)));
        }
    }
    for u in &t.uniques {
        if dialect == Dialect::MySql {
            parts.push(format!("UNIQUE KEY {} ({})", q(&u.name), cols(&u.columns)));
        } else {
            parts.push(format!("CONSTRAINT {} UNIQUE ({})", q(&u.name), cols(&u.columns)));
        }
    }
    for i in t.indexes.iter().filter(|_| dialect == Dialect::MySql) {
        parts.push(format!("{}KEY {} ({})", if i.unique { "UNIQUE " } else { "" }, q(&i.name), cols(&i.columns)));
    }
    for fk in &t.foreign_keys {
        let target = if fk.ref_schema == schema { q(&fk.ref_table) } else { format!("{}.{}", q(&fk.ref_schema), q(&fk.ref_table)) };
        let mut s =
            format!("CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})", q(&fk.name), cols(&fk.columns), target, cols(&fk.ref_columns));
        if let Some(a) = &fk.on_delete {
            s.push_str(&format!(" ON DELETE {a}"));
        }
        if let Some(a) = &fk.on_update {
            s.push_str(&format!(" ON UPDATE {a}"));
        }
        parts.push(s);
    }
    for c in &t.checks {
        parts.push(format!("CONSTRAINT {} CHECK ({})", q(&c.name), c.display));
    }
    let name = match dialect {
        Dialect::MySql => q(&t.name),
        _ => format!("{}.{}", q(schema), q(&t.name)),
    };
    let mut out = format!("CREATE TABLE {name} (\n  {}\n)", parts.join(",\n  "));
    if dialect == Dialect::MySql {
        out.push_str(" ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci");
        if let Some(c) = &t.comment {
            out.push_str(&format!(" COMMENT={}", quote_literal(c)));
        }
    } else {
        out.push(';');
        for i in &t.indexes {
            out.push_str(&format!(
                "\nCREATE {}INDEX {} ON {}.{} ({});",
                if i.unique { "UNIQUE " } else { "" },
                q(&i.name),
                q(schema),
                q(&t.name),
                cols(&i.columns)
            ));
        }
    }
    out
}

fn quote_ident_if_needed(s: &str) -> String {
    let simple = !s.is_empty()
        && s.chars().next().is_some_and(|c| c.is_ascii_lowercase() || c == '_')
        && s.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if simple { s.to_owned() } else { quote_ident(s) }
}

