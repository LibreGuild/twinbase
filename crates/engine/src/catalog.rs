/// SQL Server type facts for `sys.columns`: (type name, max_length, precision, scale).
fn mssql_type_facts(ty: &SqlType) -> (String, i64, i64, i64) {
    let text = ty.mssql_column_type();
    let (name, args) = match text.find('(') {
        Some(p) => (text[..p].to_owned(), text[p + 1..text.len() - 1].to_owned()),
        None => (text.clone(), String::new()),
    };
    let n: Vec<i64> = args.split(',').filter_map(|a| a.trim().parse().ok()).collect();
    let max = args.eq_ignore_ascii_case("max");
    match name.as_str() {
        "nvarchar" | "nchar" => (name, if max { -1 } else { n.first().copied().unwrap_or(1) * 2 }, 0, 0),
        "varchar" | "char" | "varbinary" | "binary" => (name, if max { -1 } else { n.first().copied().unwrap_or(1) }, 0, 0),
        "decimal" | "numeric" => (name, 17, n.first().copied().unwrap_or(18), n.get(1).copied().unwrap_or(0)),
        "bit" => (name, 1, 1, 0),
        "smallint" => (name, 2, 5, 0),
        "int" => (name, 4, 10, 0),
        "bigint" => (name, 8, 19, 0),
        "real" => (name, 4, 24, 0),
        "float" => (name, 8, 53, 0),
        "date" => (name, 3, 10, 0),
        "time" => (name, 5, 16, 7),
        "datetime2" => (name, 8, 27, 7),
        "datetimeoffset" => (name, 10, 34, 7),
        "uniqueidentifier" => (name, 16, 0, 0),
        _ => (name, -1, 0, 0),
    }
}

/// Build the emulated SQL Server catalog views (`sys.schemas`, `sys.objects`, `sys.columns`, …)
/// that tools and TwinBase's own SQL Server client read.
pub fn populate_mssql_sys(conn: &Connection, cat: &Catalog, types: &mut CatalogTypes) -> Result<()> {
    let mut schemas = Vec::new();
    let mut objects = Vec::new();
    let mut columns = Vec::new();
    let mut defaults = Vec::new();
    let mut indexes = Vec::new();
    let mut index_cols = Vec::new();
    let mut fks = Vec::new();
    let mut fk_cols = Vec::new();
    let mut keys = Vec::new();
    let mut type_ids: std::collections::BTreeMap<String, i64> = std::collections::BTreeMap::new();
    let mut next_object = 1_000_000_i64;
    let mut object_ids: std::collections::HashMap<(String, String), i64> = std::collections::HashMap::new();
    // dbo is schema 1, as in SQL Server; others follow.
    let mut schema_names: Vec<&String> = cat.schemas.keys().collect();
    schema_names.sort_by_key(|n| (n.as_str() != "dbo", n.to_ascii_lowercase()));
    let schema_id = |name: &str| -> i64 {
        if name == "dbo" { 1 } else { 5 + schema_names.iter().position(|n| n.as_str() == name).unwrap_or(0) as i64 }
    };
    for sd in cat.schemas.values() {
        let sid = schema_id(&sd.name);
        schemas.push(vec![t(&sd.name), i(sid), i(1)]);
        for tn in sd.tables.keys() {
            next_object += 1;
            object_ids.insert((sd.name.clone(), tn.clone()), next_object);
        }
        for vn in sd.views.keys() {
            next_object += 1;
            object_ids.insert((sd.name.clone(), vn.clone()), next_object);
        }
    }
    let mut next_constraint = 2_000_000_i64;
    for sd in cat.schemas.values() {
        let sid = schema_id(&sd.name);
        for vn in sd.views.keys() {
            objects.push(vec![t(vn), i(object_ids[&(sd.name.clone(), vn.clone())]), i(sid), t("V"), t("VIEW"), null()]);
        }
        for (tn, td) in &sd.tables {
            let oid = object_ids[&(sd.name.clone(), tn.clone())];
            objects.push(vec![t(tn), i(oid), i(sid), t("U"), t("USER_TABLE"), null()]);
            for (n, c) in td.columns.iter().enumerate() {
                let (tname, max_length, precision, scale) = mssql_type_facts(&c.ty);
                let next_type = type_ids.len() as i64 + 1;
                let tid = *type_ids.entry(tname.clone()).or_insert(next_type);
                let default_id = match (&c.default, c.default_constraint_name(tn)) {
                    (Some(d), Some(name)) => {
                        next_constraint += 1;
                        defaults.push(vec![t(&name), i(next_constraint), i(oid), i(n as i64 + 1), t(format!("({})", d.display.trim()))]);
                        objects.push(vec![t(&name), i(next_constraint), i(sid), t("D"), t("DEFAULT_CONSTRAINT"), i(oid)]);
                        next_constraint
                    }
                    _ => 0,
                };
                columns.push(vec![
                    i(oid),
                    t(&c.name),
                    i(n as i64 + 1),
                    i(tid),
                    i(tid),
                    i(max_length),
                    i(precision),
                    i(scale),
                    b(c.nullable),
                    b(c.identity.is_some()),
                    b(false),
                    i(default_id),
                ]);
            }
            let col_id = |name: &str| td.columns.iter().position(|c| c.name == name).map(|p| p as i64 + 1).unwrap_or(0);
            let mut index_id = 1;
            let mut push_index = |name: &str, cols: &[String], unique: bool, primary: bool, constraint: bool, index_id: i64| {
                indexes.push(vec![
                    i(oid),
                    t(name),
                    i(index_id),
                    i(if index_id == 1 { 1 } else { 2 }),
                    b(unique),
                    b(primary),
                    b(constraint && !primary),
                ]);
                for (k, c) in cols.iter().enumerate() {
                    index_cols.push(vec![i(oid), i(index_id), i(col_id(c)), i(k as i64 + 1), b(false)]);
                }
            };
            if let Some(pk) = &td.primary_key {
                let name = Some(pk.name.clone()).filter(|n| !n.is_empty()).unwrap_or_else(|| format!("PK__{tn}"));
                push_index(&name, &pk.columns, true, true, true, index_id);
                next_constraint += 1;
                keys.push(vec![t(&name), i(next_constraint), t("PK"), i(oid), i(sid)]);
                index_id += 1;
            }
            for u in &td.uniques {
                let name = Some(u.name.clone()).filter(|n| !n.is_empty()).unwrap_or_else(|| format!("UQ__{}__{}", tn, u.columns.join("_")));
                push_index(&name, &u.columns, true, false, true, index_id);
                next_constraint += 1;
                keys.push(vec![t(&name), i(next_constraint), t("UQ"), i(oid), i(sid)]);
                index_id += 1;
            }
            for ix in &td.indexes {
                push_index(&ix.name, &ix.columns, ix.unique, false, false, index_id);
                index_id += 1;
            }
            for f in &td.foreign_keys {
                next_constraint += 1;
                let ref_schema = Some(f.ref_schema.clone()).filter(|n| !n.is_empty()).unwrap_or_else(|| sd.name.clone());
                let ref_oid = object_ids.get(&(ref_schema.clone(), f.ref_table.clone())).copied().unwrap_or(0);
                let action = match f.on_delete.as_deref().map(|a| a.to_ascii_uppercase()) {
                    Some(a) if a == "CASCADE" => "CASCADE",
                    Some(a) if a == "SET NULL" => "SET_NULL",
                    Some(a) if a == "SET DEFAULT" => "SET_DEFAULT",
                    _ => "NO_ACTION",
                };
                let name = Some(f.name.clone()).filter(|n| !n.is_empty()).unwrap_or_else(|| format!("FK__{}__{}", tn, f.ref_table));
                fks.push(vec![t(&name), i(next_constraint), i(oid), i(ref_oid), t(action), i(sid)]);
                let ref_td = cat.table(&ref_schema, &f.ref_table);
                for (k, (c, rc)) in f.columns.iter().zip(&f.ref_columns).enumerate() {
                    let rcid = ref_td.and_then(|r| r.columns.iter().position(|x| &x.name == rc)).map(|p| p as i64 + 1).unwrap_or(0);
                    fk_cols.push(vec![i(next_constraint), i(k as i64 + 1), i(oid), i(col_id(c)), i(ref_oid), i(rcid)]);
                }
            }
        }
    }
    let types_rows: Vec<Vec<Value>> = type_ids.iter().map(|(n, id)| vec![t(n), i(*id), i(*id)]).collect();
    let defs = vec![
        CatTable { name: "schemas", columns: &[("name", "TEXT"), ("schema_id", "INT"), ("principal_id", "INT")], rows: schemas },
        CatTable {
            name: "objects",
            columns: &[
                ("name", "TEXT"),
                ("object_id", "INT"),
                ("schema_id", "INT"),
                ("type", "TEXT"),
                ("type_desc", "TEXT"),
                ("parent_object_id", "INT"),
            ],
            rows: objects.clone(),
        },
        CatTable {
            name: "tables",
            columns: &[
                ("name", "TEXT"),
                ("object_id", "INT"),
                ("schema_id", "INT"),
                ("type", "TEXT"),
                ("type_desc", "TEXT"),
                ("parent_object_id", "INT"),
            ],
            rows: objects.iter().filter(|o| matches!(&o[3], Value::Text(x) if x == "U")).cloned().collect(),
        },
        CatTable {
            name: "views",
            columns: &[
                ("name", "TEXT"),
                ("object_id", "INT"),
                ("schema_id", "INT"),
                ("type", "TEXT"),
                ("type_desc", "TEXT"),
                ("parent_object_id", "INT"),
            ],
            rows: objects.iter().filter(|o| matches!(&o[3], Value::Text(x) if x == "V")).cloned().collect(),
        },
        CatTable {
            name: "columns",
            columns: &[
                ("object_id", "INT"),
                ("name", "TEXT"),
                ("column_id", "INT"),
                ("system_type_id", "INT"),
                ("user_type_id", "INT"),
                ("max_length", "INT"),
                ("precision", "INT"),
                ("scale", "INT"),
                ("is_nullable", "BOOL"),
                ("is_identity", "BOOL"),
                ("is_computed", "BOOL"),
                ("default_object_id", "INT"),
            ],
            rows: columns,
        },
        CatTable { name: "types", columns: &[("name", "TEXT"), ("system_type_id", "INT"), ("user_type_id", "INT")], rows: types_rows },
        CatTable {
            name: "default_constraints",
            columns: &[
                ("name", "TEXT"),
                ("object_id", "INT"),
                ("parent_object_id", "INT"),
                ("parent_column_id", "INT"),
                ("definition", "TEXT"),
            ],
            rows: defaults,
        },
        CatTable {
            name: "indexes",
            columns: &[
                ("object_id", "INT"),
                ("name", "TEXT"),
                ("index_id", "INT"),
                ("type", "INT"),
                ("is_unique", "BOOL"),
                ("is_primary_key", "BOOL"),
                ("is_unique_constraint", "BOOL"),
            ],
            rows: indexes,
        },
        CatTable {
            name: "index_columns",
            columns: &[
                ("object_id", "INT"),
                ("index_id", "INT"),
                ("column_id", "INT"),
                ("key_ordinal", "INT"),
                ("is_included_column", "BOOL"),
            ],
            rows: index_cols,
        },
        CatTable {
            name: "foreign_keys",
            columns: &[
                ("name", "TEXT"),
                ("object_id", "INT"),
                ("parent_object_id", "INT"),
                ("referenced_object_id", "INT"),
                ("delete_referential_action_desc", "TEXT"),
                ("schema_id", "INT"),
            ],
            rows: fks,
        },
        CatTable {
            name: "foreign_key_columns",
            columns: &[
                ("constraint_object_id", "INT"),
                ("constraint_column_id", "INT"),
                ("parent_object_id", "INT"),
                ("parent_column_id", "INT"),
                ("referenced_object_id", "INT"),
                ("referenced_column_id", "INT"),
            ],
            rows: fk_cols,
        },
        CatTable {
            name: "key_constraints",
            columns: &[("name", "TEXT"), ("object_id", "INT"), ("type", "TEXT"), ("parent_object_id", "INT"), ("schema_id", "INT")],
            rows: keys,
        },
    ];
    create_cat_tables(conn, "sys", defs, types)
}
