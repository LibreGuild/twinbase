//! Oracle client against a real database. Needs Oracle Instant Client (`TWINBASE_ORACLE_CLIENT`, its
//! folder) and a database: `TWINBASE_REAL_ORACLE_PORT`, `TWINBASE_REAL_ORACLE_SERVICE` (e.g.
//! FREEPDB1), `TWINBASE_REAL_ORACLE_USER`, `TWINBASE_REAL_ORACLE_PASSWORD` — for example the
//! `gvenzl/oracle-free` image. Skipped otherwise.

use serde_json::json;
use twinbase_client::sqlgen::{ChangeSet, RowQuery, RowUpdate};
use twinbase_client::{Client, ConnectionConfig, DbKind, TlsMode, apply_changes, fetch_rows};

#[tokio::test]
async fn oracle_end_to_end() {
    let (Ok(port), Ok(service), Ok(user), Ok(password)) = (
        std::env::var("TWINBASE_REAL_ORACLE_PORT"),
        std::env::var("TWINBASE_REAL_ORACLE_SERVICE"),
        std::env::var("TWINBASE_REAL_ORACLE_USER"),
        std::env::var("TWINBASE_REAL_ORACLE_PASSWORD"),
    ) else {
        return;
    };
    let cfg = ConnectionConfig {
        kind: DbKind::Oracle,
        host: "127.0.0.1".into(),
        port: port.parse().unwrap(),
        user: user.clone(),
        password: Some(password),
        database: Some(service),
        path: None,
        tls: TlsMode::Disable,
        timeout_secs: 20,
        ssh: None,
        via: None,
    };
    let c = Client::connect(&cfg).await.unwrap();
    let s = c.sql().unwrap();
    assert!(s.server_version().await.unwrap().contains("Oracle"));
    let t = format!("TB_ITEMS_{}", std::process::id());
    s.query(
        &format!(
            "CREATE TABLE {t} (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR2(100 CHAR) NOT NULL, price NUMBER(10,2) DEFAULT 0, added DATE DEFAULT SYSDATE, raw RAW(16));
INSERT INTO {t} (name, price, raw) VALUES ('Lamp', 25.5, HEXTORAW('CAFE'));
INSERT INTO {t} (name) VALUES ('Desk');
BEGIN
  UPDATE {t} SET price = price + 1 WHERE name = 'Desk';
END;
/"
        ),
        10,
    )
    .await
    .unwrap();
    let r = s.query(&format!("SELECT id, name, price, raw FROM {t} ORDER BY id"), 10).await.unwrap();
    assert_eq!(r[0].rows[0][1..], [json!("Lamp"), json!("25.5"), json!("\\xcafe")]);
    let schema = s.schemas().await.unwrap()[0].clone();
    assert_eq!(schema, user.to_ascii_uppercase());
    let info = s.describe(&schema, &t).await.unwrap();
    assert_eq!(info.primary_key, vec!["ID"]);
    assert!(info.columns.iter().any(|c| c.name == "NAME" && c.data_type == "VARCHAR2(100 CHAR)" && !c.nullable));
    let page = fetch_rows(s, &schema, &t, &RowQuery { limit: 1, offset: 1, ..Default::default() }).await.unwrap();
    assert_eq!(page.total, Some(2));
    let id = page.result.rows[0][0].clone();
    let changes = ChangeSet {
        updates: vec![RowUpdate {
            key: json!({ "ID": id }).as_object().unwrap().clone(),
            values: json!({ "PRICE": 3 }).as_object().unwrap().clone(),
        }],
        ..Default::default()
    };
    assert_eq!(apply_changes(s, &schema, &t, &changes).await.unwrap().affected, 1);
    let e = s.query("SELECT * FROM nope_table_xyz", 1).await.unwrap_err();
    assert_eq!(e.code.as_deref(), Some("ORA-00942"));
    s.query(&format!("DROP TABLE {t} PURGE"), 1).await.unwrap();
}
